#!/usr/bin/env python3
"""Recompute every delivered number from the per-query and per-batch records in results/, without searching.

usage: check_results.py [--keep DIR]

1. Alpha selection: rule C and rule B for all 54 points, from the per-query calibration results of every grid alpha
   (results/quality/v4.tar.xz), compared with the selection files of the run.
2. Held-out and fresh verdicts of every arm (fixed, rule C, rule B, old, default), and the rule C+m alphas with their
   verdicts, from the per-query held-out results.
3. summary-v4.json and REPORT-v4.md regenerated by recalibrate.py's report phase from the files of steps 1-2,
   compared byte for byte with results/quality/.
4. The margin cross-validation (cv_margin.py) rerun on the calibration results: cv_margin.json and its table.
5. Timing: medians of the four repeats per point, thread count and arm, from results/timing/v6/batches.json,
   compared with timing-summary-v6.json; then make_report_assets.py regenerates report/tables.md and
   report/data/points.csv, compared byte for byte. Figures are regenerated but not compared (fonts differ by machine).
6. frozen/configurations.json against the summary.
Exit status 0 when everything matches. The working copy goes to a temporary directory (or --keep DIR).
"""
import argparse
import filecmp
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile

import numpy as np

PACKAGE = Path(__file__).resolve().parent.parent
RESULTS = PACKAGE / 'results'
failures = []


def check(name, ok, detail=''):
    print(f'{"ok  " if ok else "FAIL"} {name}' + (f'  {detail}' if detail else ''), flush=True)
    if not ok:
        failures.append(name)


def canonical(value):
    return json.loads(json.dumps(value))


def quiet(function, *args):
    """recalibrate.py prints one line per point; keep the check's own output readable."""
    stdout = sys.stdout
    sys.stdout = open(os.devnull, 'w')
    try:
        return function(*args)
    finally:
        sys.stdout.close()
        sys.stdout = stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--keep', type=Path, help='keep the recomputed files in this new directory')
    args = parser.parse_args()
    work = Path(tempfile.mkdtemp(prefix='repro-check-')) if args.keep is None else args.keep
    work.mkdir(parents=True, exist_ok=args.keep is None)
    shipped = work / 'shipped'
    with tarfile.open(RESULTS / 'quality' / 'v4.tar.xz') as tar:
        tar.extractall(shipped, filter='data')
    out = work / 'recomputed'
    for name in ['compare-v3-v4.json', 'default-check-v4.json']:
        (out).mkdir(parents=True, exist_ok=True)
        shutil.copy2(RESULTS / 'quality' / name, out / name)

    # The frozen fixed points and margins drive the selection; recalibrate.py reads them through config.py.
    os.environ['RECAL_RUN'] = str(out)
    os.environ['REPRO_CONFIG'] = str(PACKAGE / 'config.example.toml')
    sys.path.insert(0, str(PACKAGE / 'scripts'))
    import recalibrate as r

    lib = 'v4'
    points = r.fixed_points()
    for ds in r.DATASETS:
        src = shipped / 'quality' / lib / ds
        dst = out / 'quality' / lib / ds
        dst.mkdir(parents=True, exist_ok=True)
        for k in r.KS:
            # 1. selection from the per-query calibration results
            results = r.load(src / f'calibration-k{k}.json')
            selection = {}
            for (d, kk, R, C), point in sorted(points.items()):
                if d == ds and kk == k:
                    selection[r.label(k, R, C)] = r.select(results, ds, k, R, C, point)
            r.save(dst / f'selection-k{k}.json', selection)
            check(f'{ds} k{k} selection (rule C, rule B, per-alpha calibration stats)',
                  canonical(selection) == r.read(src / f'selection-k{k}.json'))
            # 2. held-out and fresh verdicts, then rule C+m
            for role in ['validation', 'fresh']:
                if not (src / f'{role}-k{k}.json').exists():
                    continue
                base = r.load(src / f'{role}-k{k}.json')
                verdicts = quiet(r.held_out, ds, k, role, selection, base)
                r.save(dst / f'{role}-result-k{k}.json', verdicts)
                check(f'{ds} k{k} {role} verdicts (fixed, rule C, rule B, old, default)',
                      canonical(verdicts) == r.read(src / f'{role}-result-k{k}.json'))
                chosen, _ = r.cm_choice(selection)
                if role == 'validation':
                    r.save(dst / f'selection-cm-k{k}.json', chosen)
                    check(f'{ds} k{k} rule C+m alphas',
                          canonical(chosen) == r.read(src / f'selection-cm-k{k}.json'))
                cm = r.load(src / f'{role}-cm-k{k}.json')
                repeated = sorted(n for n in cm if n in base)
                same = all(np.array_equal(cm[n][0], base[n][0]) and np.array_equal(cm[n][1], base[n][1])
                           for n in repeated)
                verdicts_cm = quiet(r.held_out_cm, ds, role, selection, chosen, base, cm)
                r.save(dst / f'{role}-cm-result-k{k}.json', dict(repeated_modes_identical=repeated, results=verdicts_cm))
                check(f'{ds} k{k} {role} rule C+m verdicts',
                      same and canonical(dict(repeated_modes_identical=repeated, results=verdicts_cm)) ==
                      r.read(src / f'{role}-cm-result-k{k}.json'))

    # 3. summary and report regenerated from the recomputed files only
    quiet(r.report, lib)
    for name in ['summary-v4.json', 'REPORT-v4.md']:
        check(f'{name} regenerated byte for byte', filecmp.cmp(out / name, RESULTS / 'quality' / name, shallow=False))

    # 4. margin cross-validation
    table = subprocess.run([sys.executable, str(PACKAGE / 'scripts' / 'cv_margin.py'), str(shipped / 'quality' / lib),
                            str(out / 'cv_margin.json')], check=True, capture_output=True, text=True)
    (out / 'cv_margin.txt').write_text(table.stdout)
    check('cv_margin.json regenerated byte for byte',
          filecmp.cmp(out / 'cv_margin.json', RESULTS / 'margin' / 'cv_margin.json', shallow=False))
    check('cv_margin table regenerated', table.stdout == (RESULTS / 'margin' / 'cv_margin.txt').read_text(),
          table.stderr.strip().replace('\n', '; '))

    # 5. timing medians and report tables
    rows = r.read(RESULTS / 'timing' / 'v6' / 'batches.json')
    cells = {}
    for row in rows:
        cells.setdefault((row['dataset'], row['point'], row['threads']), {}).setdefault(row['arm'], []).append(row)
    worst = 0.0
    entries = r.read(RESULTS / 'timing' / 'timing-summary-v6.json')
    for e in entries:
        arms = cells[(e['dataset'], e['point'], e['threads'])]
        med = {a: {key: float(np.median([x[key] for x in arms[a]])) for key in ['qps', 'p99_ms']} for a in arms}
        qps = 100 * (med[e['arm']]['qps'] / med['ref']['qps'] - 1)
        p99 = 100 * (med[e['arm']]['p99_ms'] / med['ref']['p99_ms'] - 1)
        worst = max(worst, abs(qps - e['qps_pct']), abs(p99 - e['p99_pct']))
    check(f'timing-summary-v6.json from batches.json ({len(entries)} entries, {len(rows)} batch rows)', worst < 1e-9,
          f'max abs diff {worst:.1e} pct points')
    report = work / 'report'
    subprocess.run([sys.executable, str(PACKAGE / 'scripts' / 'make_report_assets.py'), '--out', str(report)],
                   check=True, capture_output=True)
    for name in ['tables.md', 'data/points.csv']:
        check(f'report/{name} regenerated byte for byte',
              filecmp.cmp(report / name, PACKAGE / 'report' / name, shallow=False))

    # 6. the frozen configurations restate the summary
    summary = {(p['dataset'], p['point']): p for p in r.read(RESULTS / 'quality' / 'summary-v4.json')['points']}
    configurations = r.read(PACKAGE / 'frozen' / 'configurations.json')['points']
    ok = len(configurations) == len(summary)
    for c in configurations:
        p = summary[(c['dataset'], c['point'])]
        ok &= c['ef_search'] == p['fixed_ef'] and c['auto_off'] == p['auto_off']
        ok &= c['alpha'] == p['rule_cm_alpha'] and c['rule_c_alpha'] == p['rule_c_alpha']
    check('frozen/configurations.json matches summary-v4.json', ok)

    keep = args.keep is not None or failures
    print(f'\n{len(failures)} failed' if failures else '\nall checks passed', f'(work files in {work})' if keep else '')
    if not keep:
        shutil.rmtree(work)
    sys.exit(1 if failures else 0)


if __name__ == '__main__':
    main()
